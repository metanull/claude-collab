#!/usr/bin/env bash
# Wake-on-LAN (magic packet) on a wired port, stored on its NetworkManager profile. Run as root:
#
#   sudo bash setup-wol.sh [--iface IFACE] [--profile PROFILE]          # enable
#   sudo bash setup-wol.sh [--iface IFACE] [--profile PROFILE] --undo   # put the previous value back
#        --undo refuses if this script saved no previous value; --undo --force then writes 'default'
#   bash setup-wol.sh [--iface IFACE] --dry-run                         # no root: show what would be done
#
#   --iface    wired interface that receives the magic packet. Default: WOL_IFACE of the sudo
#              caller's ~/.config/claude-collab/config (written by install-collab.sh).
#              Example: IFACE (see `ip -br link`)
#   --profile  NetworkManager profile of that interface. Default: WOL_PROFILE of that file, else
#              the profile active on the interface (needs a link). Example: PROFILE
#
# Why the profile: on Ubuntu the profile is generated by netplan and carries its own wake-on-lan
# value, so a NetworkManager conf.d default never applies, and a one-off `ethtool -s IFACE wol g`
# is reset the next time NetworkManager activates the device (also on resume from suspend).
# Setting it on the profile survived suspend and a cold boot in our tests (docs/wake-on-lan.md).
#
# What it does (safe to run again):
#   1. Checks that the adapter supports magic-packet wake (ethtool "Supports Wake-on: ...g...").
#   2. Remembers the profile's current value in /var/lib/claude-collab/ (first run only).
#   3. nmcli connection modify PROFILE 802-3-ethernet.wake-on-lan magic
#   4. Re-activates the profile if the adapter is not armed yet (brief link drop on that port).
# Not covered: firmware settings ("Wake on LAN", "ErP", "Deep sleep") can still block the wake.
set -euo pipefail
export LC_ALL=C

usage() { sed -n '2,25p' "$0" | sed 's/^# \{0,1\}//'; }

IFACE=""; PROFILE=""; UNDO=0; DRY=0; FORCE=0
while [[ $# -gt 0 ]]; do
    case "$1" in
        --iface)   IFACE="${2:?--iface needs a value}"; shift ;;
        --profile) PROFILE="${2:?--profile needs a value}"; shift ;;
        --undo)    UNDO=1 ;;
        --force)   FORCE=1 ;;
        --dry-run) DRY=1 ;;
        -h|--help) usage; exit 0 ;;
        *) echo "Unknown argument: $1" >&2; usage >&2; exit 2 ;;
    esac
    shift
done

# Defaults from the owner's local config file (written by install-collab.sh), if there is one.
CONF_USER=${SUDO_USER:-$(id -un)}
CONF="$(getent passwd "$CONF_USER" | cut -d: -f6)/.config/claude-collab/config"
cfg_get() { [[ -r "$CONF" ]] && sed -n "s/^$1=//p" "$CONF" | head -n 1; return 0; }
[[ -n "$IFACE" ]]   || IFACE=$(cfg_get WOL_IFACE)
[[ -n "$PROFILE" ]] || PROFILE=$(cfg_get WOL_PROFILE)
[[ -n "$IFACE" ]] || { echo "No interface: give --iface IFACE, or run install-collab.sh first (it writes $CONF)." >&2; exit 2; }
[[ "$IFACE" =~ ^[A-Za-z0-9_.-]+$ ]] || { echo "Invalid interface name: $IFACE" >&2; exit 2; }
[[ -e "/sys/class/net/$IFACE" ]] || { echo "No such interface: $IFACE" >&2; exit 1; }
[[ ! -d "/sys/class/net/$IFACE/wireless" ]] || { echo "$IFACE is a Wi-Fi interface; this script is for a wired port." >&2; exit 1; }
command -v nmcli >/dev/null || { echo "nmcli not found: this script needs NetworkManager." >&2; exit 1; }
[[ $DRY -eq 1 || $EUID -eq 0 ]] || { echo "Run with sudo (or add --dry-run)." >&2; exit 1; }

if [[ -z "$PROFILE" ]]; then
    PROFILE=$(nmcli -g GENERAL.CONNECTION device show "$IFACE" 2>/dev/null || true)
    [[ -n "$PROFILE" ]] || { echo "No active NetworkManager profile on $IFACE (no link?). Give --profile NAME." >&2; exit 1; }
fi
CURRENT=$(nmcli -g 802-3-ethernet.wake-on-lan connection show "$PROFILE" 2>/dev/null) \
    || { echo "Profile '$PROFILE' not found, or it is not an ethernet profile." >&2; exit 1; }
CURRENT=${CURRENT// /}

STATE_DIR=/var/lib/claude-collab
STATE="$STATE_DIR/wol-previous-${PROFILE//[^A-Za-z0-9_.-]/_}"

run() { if [[ $DRY -eq 1 ]]; then echo "   would run: $*"; else "$@"; fi; }
runq() { if [[ $DRY -eq 1 ]]; then echo "   would run: $*"; else "$@" >/dev/null; fi; }   # same, output discarded
armed() { ethtool "$IFACE" 2>/dev/null | grep -Eq '^[[:space:]]*Wake-on:.*g'; }
show() {
    echo "   profile $PROFILE: wake-on-lan = $(nmcli -g 802-3-ethernet.wake-on-lan connection show "$PROFILE")"
    echo "   adapter: $(ethtool "$IFACE" 2>/dev/null | grep -E '^[[:space:]]*Wake-on:' | xargs || true)"
    echo "   device wakeup: $(cat "/sys/class/net/$IFACE/device/power/wakeup" 2>/dev/null || echo unknown)"
}

if [[ $UNDO -eq 1 ]]; then
    if [[ -r "$STATE" ]]; then PREV=$(<"$STATE")
    elif [[ $FORCE -eq 1 ]]; then PREV=default; echo "   no saved value in $STATE: --force, using 'default'"
    else
        echo "No saved value in $STATE: this script did not change profile '$PROFILE' (current value: '$CURRENT')." >&2
        echo "Nothing changed. To set the profile to 'default' anyway, add --force." >&2
        exit 1
    fi
    echo "== Wake-on-LAN on $IFACE: back to '$PREV' (was '$CURRENT')"
    run nmcli connection modify "$PROFILE" 802-3-ethernet.wake-on-lan "$PREV"
    runq nmcli connection up "$PROFILE" || echo "   could not re-activate $PROFILE; the value applies at the next activation"
    run rm -f -- "$STATE"
    [[ $DRY -eq 1 ]] || show
    exit 0
fi

echo "== 1. Adapter support on $IFACE"
if command -v ethtool >/dev/null && [[ $EUID -eq 0 ]]; then
    if ! ethtool "$IFACE" | grep -Eq 'Supports Wake-on:.*g'; then
        echo "The adapter does not report magic-packet support. Stopping." >&2
        ethtool "$IFACE" | grep -i wake >&2 || true
        exit 1
    fi
    echo "   magic packet supported"
else
    echo "   not checked (ethtool needs root and must be installed: apt install ethtool)"
fi

echo "== 2. Profile '$PROFILE' (current value: $CURRENT)"
if [[ "$CURRENT" == magic ]]; then
    echo "   already 'magic', profile left as it is"
else
    if [[ ! -e "$STATE" ]]; then
        if [[ $DRY -eq 1 ]]; then echo "   would save '$CURRENT' to $STATE"
        else install -d -m 755 "$STATE_DIR"; printf '%s\n' "$CURRENT" > "$STATE"; fi
    fi
    run nmcli connection modify "$PROFILE" 802-3-ethernet.wake-on-lan magic
fi

echo "== 3. Apply"
if armed; then
    echo "   adapter already armed (Wake-on: g), profile not re-activated"
elif [[ $DRY -eq 1 && $EUID -ne 0 ]]; then
    echo "   adapter state unknown without root (ethtool): a real run re-activates the profile only if it is not armed yet"
    echo "   might run: nmcli connection up $PROFILE"
else
    runq nmcli connection up "$PROFILE" || echo "   could not re-activate $PROFILE (no link?); the value applies at the next activation"
fi
[[ $DRY -eq 1 ]] || show

echo
echo "MAC address to wake: $(cat "/sys/class/net/$IFACE/address")"
echo "The magic packet must arrive on this port: send it from the adapter at the other end of this cable or segment."
